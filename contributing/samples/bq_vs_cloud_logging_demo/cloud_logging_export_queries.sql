-- ============================================================================
-- 7. WHAT YOU CAN DO WITH EXPORTED LOGS
-- ============================================================================
-- The following queries ARE useful with exported Cloud Logging data:

-- 7a. Error monitoring dashboard
SELECT
  TIMESTAMP_TRUNC(timestamp, HOUR) AS hour,
  severity,
  COUNT(*) AS count
FROM `test-project-0728-467323.cloud_logging_export.adk_otel_*`
WHERE timestamp >= TIMESTAMP_SUB(CURRENT_TIMESTAMP(), INTERVAL 24 HOUR)
GROUP BY hour, severity
ORDER BY hour DESC;

-- 7b. Log volume monitoring
SELECT
  DATE(timestamp) AS date,
  COUNT(*) AS total_logs,
  COUNTIF(severity = 'ERROR') AS errors,
  COUNTIF(severity = 'WARNING') AS warnings
FROM `test-project-0728-467323.cloud_logging_export.adk_otel_*`
WHERE timestamp >= TIMESTAMP_SUB(CURRENT_TIMESTAMP(), INTERVAL 7 DAY)
GROUP BY date
ORDER BY date DESC;

-- 7c. Trace correlation (for debugging)
SELECT
  timestamp,
  severity,
  spanId,
  LEFT(COALESCE(textPayload, TO_JSON_STRING(jsonPayload)), 100) AS preview
FROM `test-project-0728-467323.cloud_logging_export.adk_otel_*`
WHERE trace = 'projects/test-project-0728-467323/traces/YOUR_TRACE_ID'
ORDER BY timestamp;


